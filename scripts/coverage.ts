import { hfDatasetFor } from "../src/science/providers";
import { readFileSync, writeFileSync } from "node:fs";
import { ELEMENTS } from "../src/data/elements";
import { coverage } from "../src/science/coverage";
const path = 'docs/ACCURACY_MATRIX.md';
const preamble = `# Neutral-atom coverage · v0.5.0

Generated by \`npm run data:matrix\`. Rows describe the preferred **neutral** result, not a user-selected one-electron ion.

- **A** = hydrogenic-exact: analytic within the point-nucleus, infinite-mass, non-relativistic Hamiltonian.
- **S** = browser-slater: qualitative independent-electron estimate. Its energy surrogate is **not** an orbital eigenvalue. Phase/current belong to this model orbital alone.
- **HF** = pyscf-hf: converged basis-limited aug-cc-pVTZ RHF/ROHF. Total electronic energy and spherically averaged total density only. The optional HF comparison also exists for H.
- **—** = unavailable, not zero. No correlated, spin-orbit, finite-nucleus or relativistic radial observables are supplied for any element. All one-electron ions admit Model A only within its stated Hamiltonian.
- The orbital column covers signed radial function, orbital probability, radial moment, subshell contribution and optional phase/current. The density column includes the total radial distribution. Level labels preserve source notation (asterisk = odd parity; a bare J is not an LS assignment). Configuration evidence is not density evidence.

| Z | Element | Configuration | Evidence | Ground level | First IE evidence | Orbital | Total density | Orbital eigenvalue | Total energy |
|---:|---|---|---|---|---|---|---|---|---|`;
const key = (id: string | null) => id === 'hydrogenic-exact' ? 'A' : id === 'pyscf-hf' ? 'HF' : id === 'browser-slater' ? 'S' : '—';
const text = preamble+'\n'+ELEMENTS.map(e=>{
  const c=coverage(e);
  return `| ${e.Z} | ${e.symbol} | ${e.configuration.value} | ${e.configuration.evidence} | ${c.termAndJ ? '`'+c.termAndJ+'`' : '—'} | ${e.ionizationEnergy_eV.evidence} | ${key(c.orbital)} | ${key(c.totalDensity)} | ${key(c.orbitalEigenvalue)} | ${key(c.totalEnergy)} |`;
}).join('\n')+'\n';
if (process.argv.includes('--check')) { if (readFileSync(path,'utf8')!==text) throw new Error('Regenerate '+path); }
else writeFileSync(path,text);

// Machine-readable companion: every available value has a method/source; null means unavailable.
const record = (provider: string | null, evidence: string) => ({provider, evidence: provider ? evidence : 'unavailable'});
const rows = ELEMENTS.map(e => {
  const c = coverage(e);
  const orb = record(c.orbital, e.Z === 1 ? 'analytic-exact-within-stated-Hamiltonian' : 'qualitative-approximation');
  return {Z:e.Z, symbol:e.symbol,
    configuration:{...e.configuration}, groundLevel:{value:e.groundLevel, source:e.groundLevel ? e.configuration.source : null, evidence:e.groundLevel ? e.configuration.evidence : 'unavailable'},
    ionizationEnergy_eV:e.ionizationEnergy_eV, orbitalRadialFunction:orb, subshellDensity:orb, radialMoment:orb,
    totalDensity:record(c.totalDensity,c.evidence), orbitalEigenvalue:record(c.orbitalEigenvalue,orb.evidence),
    totalEnergy:record(c.totalEnergy,c.evidence), relativisticDensity:record(null,''),
    hfDataset:hfDatasetFor(e.Z) ? `src/data/hf/${e.symbol}.json` : null,
  };
});
const jsonPath='docs/coverage.json';
const json='[\n'+rows.map(r=>JSON.stringify(r)).join(',\n')+'\n]\n';
if(process.argv.includes('--check')) {if(readFileSync(jsonPath,'utf8')!==json) throw new Error('Regenerate '+jsonPath);}
else writeFileSync(jsonPath,json);
